                        fontSize: 13, color: Color(0xFFB91C1C), height: 1.4),
                  ),
                ),
              ],
            ),
          ),
        if (_aiEnabled && _suggestions.isNotEmpty) ...[
          Row(
            children: [
              const Text(
                'Mode:',
