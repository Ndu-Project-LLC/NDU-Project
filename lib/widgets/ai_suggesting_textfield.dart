              ),
              const SizedBox(width: 8),
              Switch(
                value: _isReplaceMode,
                onChanged: (value) => setState(() => _isReplaceMode = value),
                materialTapTargetSize: MaterialTapTargetSize.shrinkWrap,
              ),
              const SizedBox(width: 4),
              Text(
                _isReplaceMode ? 'Replace All' : 'Insert at Cursor',
                style: const TextStyle(fontSize: 12, color: Color(0xFF6B7280)),
              ),
            ],
          ),
          const SizedBox(height: 8),
          Wrap(
            spacing: 8,
            runSpacing: 8,
            children: _suggestions
                .map((s) => ActionChip(
                      backgroundColor: const Color(0xFFE1EEFF),
                      shape: RoundedRectangleBorder(
                          borderRadius: BorderRadius.circular(999)),
                      label: Text(
                        s,
                        style: const TextStyle(
                            fontSize: 12,
                            fontWeight: FontWeight.w600,
                            color: Color(0xFF1F2937)),
                      ),
                      avatar: const Icon(Icons.add_rounded,
                          size: 16, color: Color(0xFF1F2937)),
                      onPressed: () => _applySuggestion(s),
                    ))
                .toList(),
          ),
        ],
      ],
    );
  }

  /// Builds the list of [EditorAction]s surfaced in the Open Editor popup.
  ///
  /// Actions are gated by the same flags that previously gated each inline
  /// suffix icon — so the popup only shows items that are actually
  /// applicable to the current field state (e.g. undo/redo only appear
  /// when callbacks are wired up and the corresponding stack has entries).
  List<EditorAction> _buildEditorActions() {
    final aiAvailable = _aiEnabled && !_aiLimitReached;
    final docxAvailable = widget.enableDocxImport;
    final voiceAvailable = widget.enableAi;

    return <EditorAction>[
      if (aiAvailable)
        EditorAction(
          id: 'ai_suggest',
          icon: Icons.auto_awesome,
          label: 'AI suggest',
          tooltip: 'Generate suggestions based on project context',
          accent: const Color(0xFFF59E0B),
          onTap: _fetchSuggestions,
        ),
      if (aiAvailable)
        EditorAction(
          id: 'ai_rewrite',
          icon: Icons.spellcheck_outlined,
          label: 'AI rewrite / correct',
          tooltip: 'Polish text you have already typed',
          accent: const Color(0xFF10B981),
          onTap: _rewriteText,
        ),
      if (docxAvailable)
        EditorAction(
          id: 'docx',
          icon: Icons.upload_file,
          label: 'Import from .docx / .doc',
          tooltip: 'Extract text from a Word document',
          accent: const Color(0xFF0EA5E9),
          onTap: _isImportingDoc ? () {} : _importDocument,
          enabled: !_isImportingDoc,
        ),
      if (voiceAvailable)
        EditorAction(
          id: 'voice',
          icon: _isListening ? Icons.mic : Icons.mic_none_outlined,
          label: _isListening ? 'Stop voice input' : 'Voice input',
          tooltip: 'Tap to speak — your words will be transcribed',
          accent: const Color(0xFFFFB800),
          onTap: _toggleVoiceInput,
        ),
      if (widget.onRegenerate != null)
        EditorAction(
          id: 'regenerate',
          icon: Icons.refresh,
          label: 'Regenerate this field',
          tooltip: 'Re-run the original AI generation for this field',
          accent: const Color(0xFF2563EB),
          onTap: widget.onRegenerate!,
        ),
      if (widget.onUndo != null && widget.canUndo)
        EditorAction(
          id: 'undo',
          icon: Icons.undo,
          label: 'Undo last change',
          tooltip: 'Revert the most recent edit',
          accent: const Color(0xFF6B7280),
          onTap: widget.onUndo!,
        ),
      if (widget.onRedo != null && widget.canRedo)
        EditorAction(
          id: 'redo',
          icon: Icons.redo,
          label: 'Redo last change',
          tooltip: 'Re-apply the most recently undone edit',
          accent: const Color(0xFF6B7280),
          onTap: widget.onRedo!,
        ),
      if (_controller.text.isNotEmpty)
        EditorAction(
          id: 'clear',
          icon: Icons.delete_sweep,
          label: 'Clear all content',
          tooltip: 'Remove everything in this field',
          accent: const Color(0xFFEF4444),
          isDestructive: true,
          onTap: () {
            _controller.clear();
            setState(() {});
          },
        ),
    ];
  }
}

